"""Summarize existing LINEAR_USE/CGAL diagnostics without repeating CGAL.

The GeoJSON files generated by cgal_original_line_assignment contain
one feature per line. Read them one line at a time: the unassigned
polygons file can be very large, and its geometries are not needed.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re


POSITIVE=re.compile(r'"positive_length_hits"\s*:\s*(\d+)')
BOUNDARY=re.compile(r'"boundary_only_hits"\s*:\s*(\d+)')
TOUCHED=re.compile(r'"intersecting_lines"\s*:\s*(\d+)')
REASON=re.compile(r'"reason"\s*:\s*"([^"]+)"')
OBJECT_ID=re.compile(r'"object_id"\s*:\s*"([^"]+)"')


def _values(path,expressions):
	if not path.is_file():
		raise FileNotFoundError(path)
	with path.open(encoding="utf-8") as stream:
		for line_no,line in enumerate(stream,1):
			# Each feature is written on its own line. Never load geometry.
			found=[expr.search(line) for expr in expressions]
			if not any(found):
				continue
			if not all(found):
				raise ValueError(f"{path}:{line_no}: unvollständige Eigenschaften")
			yield [m.group(1) for m in found]


def summarize(prefix):
	prefix=Path(prefix)
	report_path=prefix.with_name(prefix.name+"__zuordnungsbericht.json")
	multiple_path=prefix.with_name(prefix.name+"__linien_mehrere_flaechen.geojson")
	unassigned_path=prefix.with_name(
		prefix.name+"__flaechen_ohne_eindeutige_edge_id.geojson")
	report=json.loads(report_path.read_text(encoding="utf-8"))
	if report.get("schema")!="original-line-polygon-intersections-v1":
		raise ValueError("Unerwartetes Zuordnungsbericht-Format")
	positive=Counter()
	boundary=Counter()
	real_multiple=[]
	multi_count=0
	for p,b,object_id in _values(
			multiple_path,(POSITIVE,BOUNDARY,OBJECT_ID)):
		p,b=int(p),int(b)
		positive["0" if p==0 else "1" if p==1 else "2+"]+=1
		boundary["0" if b==0 else "1" if b==1 else "2+"]+=1
		multi_count+=1
		if p>=2 and len(real_multiple)<10:
			real_multiple.append({"object_id":object_id,
				"positive_length_hits":p,"boundary_only_hits":b})
	unassigned=Counter()
	unassigned_by_reason=Counter()
	unassigned_count=0
	for touched,reason in _values(unassigned_path,(TOUCHED,REASON)):
		n=int(touched)
		unassigned["0" if n==0 else "1" if n==1 else "2+"]+=1
		unassigned_by_reason[reason]+=1
		unassigned_count+=1
	if multi_count!=report["lines_multiple_polygons"]:
		raise ValueError("Zahl der Mehrfachtreffer stimmt nicht mit Bericht überein")
	if unassigned_count!=report["polygons_without_unambiguous_edge_id"]:
		raise ValueError("Zahl der unzugeordneten Flächen stimmt nicht mit Bericht überein")
	return {
		"source_lines":report["line_count"],
		"candidate_polygons":report["polygon_count"],
		"lines_exactly_one_polygon":report["lines_exactly_one_polygon"],
		"lines_multiple_polygons":multi_count,
		"lines_no_polygon":report["lines_no_polygon"],
		"multiple_positive_length_hits":dict(positive),
		"multiple_boundary_only_hits":dict(boundary),
		"examples_multiple_positive_length":real_multiple,
		"unassigned_polygons":unassigned_count,
		"unassigned_polygons_by_intersecting_source_lines":dict(unassigned),
		"unassigned_polygons_by_reason":dict(unassigned_by_reason),
		"edge_id_conflicts":report["polygons_conflicting_edge_ids"],
	}


def main():
	parser=argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--prefix",type=Path,required=True,
		help="Basispfad ohne __suffix, z.B. output/cgal_original_line_intersections_sis_wien")
	args=parser.parse_args()
	print(json.dumps(summarize(args.prefix),ensure_ascii=False,indent=2))


if __name__=="__main__":
	main()
